function toSkill(c: Cfg, s: SkillCfg, levelReq: number): ActiveSkillDef {
  return {
    id: s.id,
    name: s.name,
    description: s.desc,
    manaCost: s.mana,
    cooldown: s.cd,
    element: s.el,
    iconKey: s.icon,
    powerMultiplier: s.mult,
    effectType: 'creature',
    levelReq,
    classes: [c.id],
    grantsExtraTurn: s.extraTurn,
    kind: 'class',
    fx: s.fx,
  };
}

function toClass(c: Cfg): HeroClassDef {
  return {
    id: c.id,
    name: c.name,
    title: c.title,
    roleDesc: c.role,
    passiveName: c.pName,
    passiveDesc: c.pDesc,
    preferredWeapons: c.weapons,
    preferredArmor: c.armor,
    offhandCategory: c.offhand,
    themeColor: c.theme,
    accentColor: c.theme,
    isCreature: true,
    unlockCost: { gold: c.cost[0], crystals: c.cost[1] },
    gemAffinity: c.gem,
    innatePassives: c.innate,
    starterGear: {
      weapon: c.gear[0],
      offhand: c.gear[1],
      chest: c.gear[2],
      helmet: c.gear[3],
      element: c.gearEl,
    },
    baseStats: {
      health: c.base[0],
      attack: c.base[1],
      defense: c.base[2],
      critChance: c.base[3],
      critDamage: c.base[4],
      mana: c.base[5],
      dodge: c.base[6],
      elementalDamage: c.base[7],
    },
    perLevelStats: {
      health: c.lvl[0],
      attack: c.lvl[1],
      defense: c.lvl[2],
      mana: c.lvl[3],
      critChance: c.lvl[4],
      elementalDamage: c.lvl[5],
    },
    ultimateSkill: {
      id: `ult_${c.id}`,
      name: c.ult.name,
      description: c.ult.desc,
      manaCost: 0,
      ultiCost: 100,
      cooldown: 0,
      element: c.ult.el,
      iconKey: c.ult.icon,
      powerMultiplier: c.ult.mult,
      effectType: 'ultimate',
      fx: c.ult.fx,
    },
    skillTree: buildTree(c.id.slice(0, 4), c.names, c.picks),
  };
}

